SP.byId = function (id) {
  for (var i = 0; i < SP.games.length; i++) if (SP.games[i].id === id) return SP.games[i];
  return null;
};

SP.best = {
  get: function (id) { try { return +localStorage.getItem('sp-best-' + id) || 0; } catch (e) { return 0; } },
  set: function (id, v) {
    try {
      if (v > SP.best.get(id)) { localStorage.setItem('sp-best-' + id, String(v)); return true; }
    } catch (e) {}
    return false;
  }
};

SP.fmt = function (n) { return Number(n).toLocaleString('zh-TW'); };
